/// A project that exercises every feature MPPKit can write, for checking a
/// reader, a writer or an app against one known file.
///
/// | Feature | Where |
/// |---|---|
/// | four-level outline, summary rows | Design › Detailed design › Interfaces › … |
/// | links FS / SS / FF / SF, lag, lead | Architecture, Data model, UI design, Backend, Lessons learned |
/// | link on a summary task | Detailed design → Design review |
/// | all eight constraints | see `constraint` on each task |
/// | milestones, incl. a flagged one with duration | Requirements sign-off, Design review, Go-live, Closure report |
/// | duration units m / h / d / w / mo, estimated | Smoke test, Kick-off meeting, …, UI design, Hypercare |
/// | manual scheduling | Security audit |
/// | progress 100 / 60 / 50 / 25 % | Kick-off meeting, Concept design, Architecture, Backend |
/// | task types, effort driven, priority | Concept design, Integration testing, Security audit |
/// | task calendars | Night batch import (Night Shift), Server burn-in (24 Hours) |
/// | deadlines | Requirements sign-off, Go-live |
/// | notes with escapes, Unicode and emoji | Kick-off meeting, Hypercare |
/// | custom WBS code | Hypercare |
/// | Text4/5/30, Number1/20, Date1/10, Flag1/20 | Concept design, Hypercare |
/// | baselines 0 and 1 with variance after them | every task; Backend slipped |
/// | resources, units 50–300 %, multi-resource tasks | five resources |
/// | Standard calendar edits and holidays, extra base calendars | four calendars |
/// | project metadata, status date, currency, calendar options | `Project` fields |
public enum SampleProject {
    public static let title = "MPPKit Feature Sample"

    public static func make() -> Project {
        var p = Project(title: title, start: MPPTime.date(2026, 1, 5, 8))
        p.author = "MPPKit"
        p.subject = "Every feature MPPKit reads and writes"
        p.keywords = "sample, test, mpp"
        p.comments = "Generated by MPPKit. Safe to share: contains no real project data."
        p.manager = "Sam Planner"
        p.company = "MPPKit Sample Co."
        p.category = "Test fixture"
        p.statusDate = MPPTime.date(2026, 3, 2, 17)
        p.currencySymbol = "€"
        p.currencyCode = "EUR"
        p.minutesPerDay = 480
        p.minutesPerWeek = 2_400
        p.daysPerMonth = 20
        p.defaultStartTime = 8 * 60
        p.defaultFinishTime = 17 * 60

        p.calendar = standardCalendar
        p.calendars = extraCalendars
        p.resources = resources
        p.tasks = tasks
        p.relations = relations
        p.assignments = assignments

        do {
            try Scheduler.schedule(&p)
        } catch {
            preconditionFailure("the sample project must schedule: \(error)")
        }
        // Baseline the plan as agreed, then a re-plan, then let Backend slip
        // so the baseline variance is visible.
        p.setBaseline(slot: 0)
        p.setBaseline(slot: 1)
        if let i = p.tasks.firstIndex(where: { $0.uid == 13 }) { p.tasks[i].durationDays = 12 }
        try? Scheduler.schedule(&p)
        return p
    }

    // MARK: - Calendars

    static let workingDay: [ClosedRange<Int>] = [480...720, 780...1020]

    static var standardCalendar: ProjectCalendar {
        var c = ProjectCalendar(name: "Standard")
        for d in 2...6 { c.week[d] = workingDay }
        c.week[1] = .some(nil)
        c.week[7] = .some(nil)
        c.exceptions = [
            CalendarException(start: MPPTime.date(2026, 1, 1), name: "New Year's Day"),
            CalendarException(start: MPPTime.date(2026, 2, 16), finish: MPPTime.date(2026, 2, 17),
                              name: "Company offsite"),
            CalendarException(start: MPPTime.date(2026, 4, 3), finish: MPPTime.date(2026, 4, 6), name: "Easter"),
            CalendarException(start: MPPTime.date(2026, 12, 24), finish: MPPTime.date(2026, 12, 26),
                              name: "Christmas"),
        ]
        return c
    }

    static var extraCalendars: [ProjectCalendar] {
        var night = ProjectCalendar(name: "Night Shift")
        for d in 2...6 { night.week[d] = [1_080...1_380] }        // 18:00–23:00
        night.week[1] = .some(nil)
        night.week[7] = .some(nil)

        var allDay = ProjectCalendar(name: "24 Hours")
        for d in 1...7 { allDay.week[d] = [0...1_440] }

        var sixDay = ProjectCalendar(name: "Six-Day Week")
        for d in 2...7 { sixDay.week[d] = [420...660, 720...960] } // 07–11, 12–16
        sixDay.week[1] = .some(nil)
        sixDay.exceptions = [CalendarException(start: MPPTime.date(2026, 5, 1), name: "Labour Day")]

        var fourDay = ProjectCalendar(name: "Four-Day Week")
        for d in 2...5 { fourDay.week[d] = [420...720, 750...1_050] } // 07–12, 12:30–17:30
        fourDay.week[6] = .some(nil)
        return [night, allDay, sixDay, fourDay]
    }

    // MARK: - Resources

    static var resources: [Resource] {
        func r(_ uid: Int, _ name: String, _ initials: String, _ email: String = "", max: Double = 1) -> Resource {
            var x = Resource(uid: uid, name: name)
            x.initials = initials
            x.email = email
            x.maxUnits = max
            return x
        }
        return [
            r(1, "Alex Morgan", "AM", "alex.morgan@example.com"),
            r(2, "Priya Shah", "PS", "priya.shah@example.com"),
            r(3, "Jonas Berg", "JB", max: 0.5),
            r(4, "Design Studio", "DS", max: 3),
            r(5, "Zoë Ünïcødé 日本", "ZU"),
        ]
    }

    // MARK: - Tasks

    static var tasks: [ProjectTask] {
        var out: [ProjectTask] = []
        func add(_ uid: Int, _ name: String, level: Int, parent: Int, days: Double = 1,
                 _ configure: (inout ProjectTask) -> Void = { _ in }) {
            var t = ProjectTask(uid: uid, name: name)
            t.outlineLevel = level
            t.parentUID = parent
            t.durationDays = days
            configure(&t)
            out.append(t)
        }

        add(1, "Initiation", level: 1, parent: 0)
        add(2, "Kick-off meeting", level: 2, parent: 1, days: 0.5) {
            $0.durationUnits = "h"
            $0.percentComplete = 100
            $0.notes = "Agenda:\n1. Scope {in} and {out}\n2. Roles \\ responsibilities\n"
                + "Attendees: Zoë, Jonas 🚀 — ünïcødé ok"
        }
        add(3, "Requirements sign-off", level: 2, parent: 1, days: 0) {
            $0.deadline = MPPTime.date(2026, 1, 9, 17)
            $0.flags[1] = true
        }

        add(4, "Design", level: 1, parent: 0)
        add(5, "Concept design", level: 2, parent: 4, days: 5) {
            $0.percentComplete = 60
            $0.priority = 800
            $0.taskType = "fixed_work"
            $0.effortDriven = true
            // Text1–3 often carry value lists in real templates, which only
            // accept list entries; free text goes in fields without one.
            $0.text[4] = "Text four"
            $0.text[5] = "Ünïcødé text"
            $0.numbers[1] = 42.5
            $0.dateFields[1] = MPPTime.date(2026, 1, 15, 9)
            $0.flags[2] = true
        }
        add(6, "Detailed design", level: 2, parent: 4)
        add(7, "Architecture", level: 3, parent: 6, days: 3) {
            $0.estimated = true
            $0.percentComplete = 50
        }
        add(8, "Data model", level: 3, parent: 6, days: 10) { $0.durationUnits = "w" }
        add(9, "Interfaces", level: 3, parent: 6)
        add(10, "API contract", level: 4, parent: 9, days: 2)
        add(11, "Event schema", level: 4, parent: 9, days: 1.5)
        add(12, "Design review", level: 2, parent: 4, days: 0) {
            $0.constraint = "MSO"
            $0.constraintDate = MPPTime.date(2026, 2, 13, 17)
        }

        add(20, "Build", level: 1, parent: 0)
        add(13, "Backend", level: 2, parent: 20, days: 10) {
            $0.percentComplete = 25
            $0.constraint = "SNET"
            $0.constraintDate = MPPTime.date(2026, 2, 18, 8)
        }
        add(14, "Frontend", level: 2, parent: 20, days: 8) { $0.constraint = "ALAP" }
        add(15, "UI design", level: 2, parent: 20, days: 20) { $0.durationUnits = "mo" }
        add(16, "Night batch import", level: 2, parent: 20, days: 3) { $0.calendar = "Night Shift" }
        add(17, "Server burn-in", level: 2, parent: 20, days: 1) { $0.calendar = "24 Hours" }
        add(18, "Security audit", level: 2, parent: 20, days: 2) {
            $0.manual = true
            $0.priority = 1000
            $0.start = MPPTime.date(2026, 3, 9, 8)
            $0.finish = MPPTime.date(2026, 3, 10, 17)
        }
        add(19, "Integration testing", level: 2, parent: 20, days: 5) {
            $0.taskType = "fixed_duration"
            $0.constraint = "FNET"
            $0.constraintDate = MPPTime.date(2026, 3, 27, 17)
        }
        add(21, "Smoke test", level: 2, parent: 20, days: 0.1875) { $0.durationUnits = "m" }

        add(30, "Launch", level: 1, parent: 0)
        add(31, "Go-live", level: 2, parent: 30, days: 0) {
            $0.constraint = "MFO"
            $0.constraintDate = MPPTime.date(2026, 4, 10, 17)
            $0.deadline = MPPTime.date(2026, 4, 17, 17)
        }
        add(32, "Hypercare", level: 2, parent: 30, days: 10) {
            $0.estimated = true
            $0.durationUnits = "w"
            $0.constraint = "SNLT"
            $0.constraintDate = MPPTime.date(2026, 4, 20, 8)
            $0.wbs = "L.HC-1"
            $0.notes = "Support window after go-live.\nEscalation: on-call rota."
            $0.text[30] = "Last text field"
            $0.numbers[20] = -1.25
            $0.dateFields[10] = MPPTime.date(2026, 4, 24, 17)
            $0.flags[20] = true
        }
        add(33, "Lessons learned", level: 2, parent: 30, days: 1) {
            $0.constraint = "FNLT"
            $0.constraintDate = MPPTime.date(2026, 5, 29, 17)
        }
        add(34, "Closure report", level: 2, parent: 30, days: 1) { $0.milestone = true }
        return out
    }

    static var relations: [Relation] {
        [
            Relation(predUID: 2, succUID: 3),                                   // FS
            Relation(predUID: 3, succUID: 5),
            Relation(predUID: 5, succUID: 7, type: "FS", lagDays: 1),           // lag
            Relation(predUID: 7, succUID: 8, type: "SS", lagDays: 2),           // SS + lag
            Relation(predUID: 7, succUID: 10),
            Relation(predUID: 10, succUID: 11, type: "SS"),
            Relation(predUID: 6, succUID: 12),                                  // from a summary
            Relation(predUID: 12, succUID: 13, type: "FS", lagDays: -2),        // lead
            Relation(predUID: 13, succUID: 14, type: "SS", lagDays: 3),
            Relation(predUID: 8, succUID: 15, type: "FF"),                      // FF
            Relation(predUID: 13, succUID: 16),
            Relation(predUID: 16, succUID: 17),
            Relation(predUID: 13, succUID: 19, type: "FF", lagDays: 1),
            Relation(predUID: 14, succUID: 19),
            Relation(predUID: 19, succUID: 21),
            Relation(predUID: 21, succUID: 31),
            Relation(predUID: 31, succUID: 32),
            Relation(predUID: 32, succUID: 33, type: "SF"),                     // SF
            Relation(predUID: 33, succUID: 34),
        ]
    }

    static var assignments: [Assignment] {
        [
            Assignment(taskUID: 2, resourceUID: 1),
            Assignment(taskUID: 2, resourceUID: 2),
            Assignment(taskUID: 5, resourceUID: 2),
            Assignment(taskUID: 5, resourceUID: 3, units: 0.5),
            Assignment(taskUID: 7, resourceUID: 1),
            Assignment(taskUID: 13, resourceUID: 1),
            Assignment(taskUID: 14, resourceUID: 2),
            Assignment(taskUID: 14, resourceUID: 5),
            // A task calendar with no working time in common with its
            // resources' calendars collapses to zero in Project, so the
            // overnight task stays unassigned.
            Assignment(taskUID: 15, resourceUID: 4, units: 3),
            Assignment(taskUID: 19, resourceUID: 3, units: 0.5),
            Assignment(taskUID: 32, resourceUID: 5),
        ]
    }
}
